"use strict";

// Builds the two data files the page loads:
//   corpus-stats.js   letter / bigram / trigram counts and a common-word list,
//                     all computed from Pride and Prejudice (training corpus)
//   test-text.js      cleaned text of A Tale of Two Cities, used only to draw
//                     test plaintexts, so training and test text never overlap
//
// usage: node tools/build-corpus.js

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");

function gutenbergBody(file) {
  const raw = fs.readFileSync(path.join(ROOT, "corpus", file), "utf8");
  const start = raw.indexOf("\n", raw.indexOf("*** START OF THE PROJECT GUTENBERG"));
  const end = raw.indexOf("*** END OF THE PROJECT GUTENBERG");
  return raw.slice(start + 1, end);
}

// curly quotes -> straight, drop everything outside printable ASCII, squeeze spaces
function cleanText(s) {
  return s
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[–—]/g, "-")
    .replace(/_/g, "")
    .replace(/[^\x20-\x7E\n]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

const train = cleanText(gutenbergBody("pride-and-prejudice.txt"));
const test = cleanText(gutenbergBody("tale-of-two-cities.txt"));

const letters = train.toUpperCase().replace(/[^A-Z]/g, "");
const idx = (c) => c.charCodeAt(0) - 65;

const uni = new Array(26).fill(0);
const bi = new Array(26 * 26).fill(0);
const tri = new Array(26 * 26 * 26).fill(0);
for (let i = 0; i < letters.length; i++) {
  const a = idx(letters[i]);
  uni[a]++;
  if (i + 1 < letters.length) bi[a * 26 + idx(letters[i + 1])]++;
  if (i + 2 < letters.length) tri[(a * 26 + idx(letters[i + 1])) * 26 + idx(letters[i + 2])]++;
}

const wordCounts = new Map();
for (const w of train.toLowerCase().split(/[^a-z]+/)) {
  if (!w) continue;
  wordCounts.set(w, (wordCounts.get(w) || 0) + 1);
}
const topWords = [...wordCounts.entries()]
  .sort((a, b) => b[1] - a[1])
  .slice(0, 1000)
  .map(([w]) => w);

const stats = {
  source: "Jane Austen, Pride and Prejudice (Project Gutenberg #1342)",
  totalLetters: letters.length,
  totalChars: train.length,
  uni,
  bi,
  tri,
  topWords,
};

fs.writeFileSync(
  path.join(ROOT, "corpus-stats.js"),
  "// generated by tools/build-corpus.js -- do not edit by hand\n" +
    "var CORPUS_STATS = " + JSON.stringify(stats) + ";\n" +
    'if (typeof module !== "undefined") module.exports = CORPUS_STATS;\n'
);

fs.writeFileSync(
  path.join(ROOT, "test-text.js"),
  "// generated by tools/build-corpus.js -- Charles Dickens, A Tale of Two Cities (Project Gutenberg #98)\n" +
    "var TEST_TEXT = " + JSON.stringify(test) + ";\n" +
    'if (typeof module !== "undefined") module.exports = TEST_TEXT;\n'
);

console.log(`training corpus: ${train.length} chars, ${letters.length} letters, ${wordCounts.size} distinct words`);
console.log(`test text:       ${test.length} chars, ${test.replace(/[^A-Za-z]/g, "").length} letters`);
console.log(
  "letter frequencies (%):",
  uni
    .map((c, i) => [String.fromCharCode(65 + i), ((100 * c) / letters.length).toFixed(2)])
    .sort((a, b) => b[1] - a[1])
    .map(([l, f]) => `${l}=${f}`)
    .join(" ")
);
console.log("top 20 words:", topWords.slice(0, 20).join(" "));
